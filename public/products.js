window.mergeRaizesProducts = (storedProducts) => {
  const productsById = new Map(
    window.RAIZES_DEFAULT_PRODUCTS.map((product) => [product.id, { ...product }])
  );

  if (Array.isArray(storedProducts)) {
    storedProducts.forEach((product) => {
      const defaults = productsById.get(product.id);
      productsById.set(product.id, defaults ? { ...defaults, ...product } : product);
    });
  }

  return [...productsById.values()];
};

window.getRaizesProductFallbackImage = (product) => {
  if (typeof product.imagem === "string" && /^data:image\/jpeg;base64,/.test(product.imagem)) {
    return product.imagem;
  }

  if (typeof product.imagem === "string" && /^\/images\/products\/[a-z0-9-]+\.jpg$/.test(product.imagem)) {
    return `.${product.imagem}`;
  }

  const photos = {
    Lanches: ["sandwich", "burger", "grilled-platter-01", "food-bowl-01", "steak-plate"],
    Pratos: ["grilled-platter-02", "braised-meat", "steak-plate", "fish-plate", "soup", "food-bowl-02", "food-bowl-03"],
    Bebidas: ["iced-drink", "juice", "cold-drink"],
    Sobremesas: ["cake", "dessert-plate", "sweet-treat", "cookies"],
    Ofertas: ["grilled-platter-01", "food-bowl-01", "burger", "fish-plate", "cake", "iced-drink", "steak-plate"]
  };
  const categoryPhotos = photos[product.categoria] || photos.Ofertas;
  const productId = Number.isFinite(Number(product.id)) ? Math.abs(Number(product.id)) : 0;
  const photoName = categoryPhotos[productId % categoryPhotos.length];
  return `./images/products/${photoName}.jpg`;
};

window.getRaizesProductImage = (product) => {
  if (typeof product.imagem === "string" && /^data:image\/jpeg;base64,/.test(product.imagem)) {
    return product.imagem;
  }

  if (typeof product.imagem === "string" && /^\/images\/products\/[a-z0-9-]+\.jpg$/.test(product.imagem)) {
    return `.${product.imagem}`;
  }

  const fileName = aiProductImages[product.id] || `${String(product.nome || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()}.png`;
  return `./imagens/${encodeURIComponent(fileName)}`;
};

window.bindRaizesProductImageFallbacks = (container) => {
  container?.querySelectorAll("img[data-product-fallback]").forEach((image) => {
    image.addEventListener("error", () => {
      if (image.dataset.fallbackUsed) return;
      image.dataset.fallbackUsed = "true";
      image.src = image.dataset.productFallback;
    }, { once: true });
  });
};

